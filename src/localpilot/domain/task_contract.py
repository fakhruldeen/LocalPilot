"""Shared domain contracts and data models for tasks, diagnostics, benchmarks, search, and voice."""

from __future__ import annotations
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class TaskCategory(str, Enum):
    TEXT = "text"
    CODE = "code"
    RETRIEVAL = "retrieval"
    AUDIO = "audio"
    MULTIMODAL = "multimodal"
    STRUCTURED = "structured"


class TaskStatus(str, Enum):
    PENDING = "pending"
    RUNNING = "running"
    SUCCESS = "success"
    FAILED = "failed"


class TaskDescriptor(BaseModel):
    """Specification of an available AI task capability."""
    task_id: str
    name: str
    category: TaskCategory
    description: str
    required_capabilities: List[str] = Field(default_factory=list)
    preferred_model_tags: List[str] = Field(default_factory=list)
    example_usage: str = ""
    inputs_schema: Dict[str, Any] = Field(default_factory=dict)
    outputs_schema: Dict[str, Any] = Field(default_factory=dict)


class TaskPlan(BaseModel):
    """Execution plan for invoking a task."""
    task_id: str
    model_alias: str
    input_summary: str
    parameters: Dict[str, Any] = Field(default_factory=dict)


class TaskArtifact(BaseModel):
    """Artifact generated by a task run."""
    artifact_id: str
    run_id: str
    name: str
    artifact_type: str  # "text", "markdown", "json", "audio"
    content: str
    created_at: str


class TaskRun(BaseModel):
    """Record of a task execution."""
    run_id: str
    task_id: str
    model_alias: str
    status: TaskStatus
    input_summary: str
    output_text: Optional[str] = None
    duration_ms: float = 0.0
    tokens_used: int = 0
    error_message: Optional[str] = None
    created_at: str
    artifacts: List[TaskArtifact] = Field(default_factory=list)


class FindingSeverity(str, Enum):
    INFO = "info"
    WARNING = "warning"
    ERROR = "error"


class DiagnosticFinding(BaseModel):
    """Specific finding produced by the doctor service."""
    finding_id: str
    category: str  # "system", "runtime", "gateway", "model", "connection", "tool"
    target_id: Optional[str] = None
    severity: FindingSeverity
    title: str
    message: str
    can_repair: bool = False
    repair_action: Optional[str] = None
    remediation_suggestion: Optional[str] = None


class RepairPlan(BaseModel):
    """Actionable repair recipe for a diagnostic finding."""
    plan_id: str
    finding_id: str
    action: str
    description: str
    risk_level: str = "low"  # "low", "medium", "high"
    requires_confirmation: bool = True


class RepairResult(BaseModel):
    """Result of applying a repair plan."""
    plan_id: str
    success: bool
    message: str
    details: Dict[str, Any] = Field(default_factory=dict)


class BenchmarkRun(BaseModel):
    """Result of a benchmark test trial."""
    run_id: str
    model_alias: str
    version_id: Optional[str] = None
    suite_name: str
    prompt_tokens: int
    completion_tokens: int
    ttft_ms: float
    tps: float
    total_duration_ms: float
    peak_memory_mb: float = 0.0
    created_at: str
    raw_metrics: Dict[str, Any] = Field(default_factory=dict)


class BenchmarkComparison(BaseModel):
    """Comparison between two or more benchmark runs."""
    suite_name: str
    runs: List[BenchmarkRun]
    winner_alias: Optional[str] = None
    speedup_ratio: float = 1.0


class SearchCollection(BaseModel):
    """Registered document collection for local retrieval."""
    collection_id: str
    name: str
    path: str
    file_count: int = 0
    passage_count: int = 0
    last_indexed_at: str
    status: str = "ready"


class SearchPassage(BaseModel):
    """Individual chunked passage inside a collection."""
    passage_id: str
    collection_id: str
    file_path: str
    relative_path: str
    line_start: int
    line_end: int
    content: str
    score: float = 0.0


class SearchResult(BaseModel):
    """Grounded answer with citations from local passages."""
    query: str
    answer: str
    sources: List[SearchPassage] = Field(default_factory=list)


class VoiceDirection(str, Enum):
    STT = "stt"
    TTS = "tts"
    CONVERSATION = "conversation"


class VoiceRun(BaseModel):
    """Record of a voice interaction."""
    run_id: str
    direction: VoiceDirection
    model: str
    duration_ms: float
    audio_seconds: float = 0.0
    transcript: Optional[str] = None
    status: str = "completed"
    error_message: Optional[str] = None
    created_at: str
