def make_candidate(
    cid: str,
    mid: str,
    name: str,
    alias: str,
    family: str,
    arch: str,
    tasks: list[TaskCategory],
    params: str,
    sz_mb: float,
    ram_mb: float,
    ctx: int = 8192,
    release: str = "2024-01-01T00:00:00Z",
    auth: bool = False,
    official: bool = False,
    pub: str = "",
    official_url: str = None,
    source: str = "huggingface",
    artifact: str = None,
    license_name: str = "Apache-2.0",
    langs: list[str] = None,
) -> NormalizedCandidate:
    art = artifact or f"{cid}.gguf"
    src_u = f"https://huggingface.co/{mid}" if source == "huggingface" else (official_url or "https://ollama.com")
    down_u = f"https://huggingface.co/{mid}/resolve/main/{art}" if source == "huggingface" else None
    return NormalizedCandidate(
        candidate_id=cid,
        model_id=mid,
        name=name,
        short_alias=alias,
        source=source,
        revision="main",
        artifact_id=art,
        equivalence_group=alias.split(":")[0],
        architecture=arch,
        family=family,
        tasks=tasks,
        languages=langs or ["en"],
        parameter_count=params,
        format="gguf",
        total_bytes=int(sz_mb * 1024 * 1024),
        files=[art],
        source_url=src_u,
        download_url=down_u,
        runtime="llamacpp",
        execution_mode=ExecutionMode.AUTO,
        usable_context=ctx,
        advertised_max_context=ctx,
        target_context=min(ctx, 4096),
        verified_release_at=release,
        metadata_fetched_at=NOW_ISO,
        requires_auth=auth,
        license=license_name,
        estimated_ram_bytes=int(ram_mb * 1024 * 1024),
        estimated_vram_bytes=int(ram_mb * 0.9 * 1024 * 1024),
        estimated_disk_bytes=int(sz_mb * 1.1 * 1024 * 1024),
        temp_disk_bytes=int(sz_mb * 0.2 * 1024 * 1024),
        confidence=ConfidenceLevel.VERIFIED,
        verification_stage=VerificationStage.SUPPORTED,
        provenance={"catalog": "seed", "publisher": pub or family, "is_official": official},
        is_official=official,
        official_resource_url=official_url,
    )

